def load_seeds() -> tuple[list[int], int]:
    """Load (headline_seeds, frozen_defaults_seed) from seeds.json."""
    data = json.loads(SEEDS_JSON.read_text(encoding="utf-8"))
    return list(data["headline_seeds"]), int(data["frozen_defaults_seed"])


# ---------------------------------------------------------------------------
# Ingestion: AMP txt -> methylstore
# ---------------------------------------------------------------------------


def _convert_cell(src_dir: Path, cov: int, cache_dir: Path) -> Path:
    """Convert N_SAMPLES AMP files for one cell to .cov.gz under cache_dir.

    Idempotent: existing files are kept (``amp_to_bismark_cov`` short-circuits
    when the destination exists). Returns ``cache_dir`` (caller passes this
    on to ``write_samplesheet``).
    """
    cache_dir.mkdir(parents=True, exist_ok=True)
    for i in range(1, N_SAMPLES + 1):
        src = src_dir / f"amp.coverage={cov}.sample{i}.txt"
        dst = cache_dir / f"sample{i}.cov.gz"
        amp_to_bismark_cov(src, dst)
    return cache_dir


# ---------------------------------------------------------------------------
# Per-cell DMC runner
# ---------------------------------------------------------------------------


def _score_cell(
    epy_df: pl.DataFrame, truth: pl.DataFrame, *, scenario: str,
    seed: int | None, coverage: int, tool: str, test: str,
    wall_s: float,
) -> dict:
    """Single-row scoring for one (engine, cell) result.

    Emits a single row at threshold_kind='qvalue', threshold=Q_THRESHOLD
    (q<0.05). The held-out simulator scoring is one-row-per-cell rather
    than the full P_THRESHOLDS sweep used by Task 2: the goal here is
    variance across seeds at the canonical operating point, not a full
    threshold scan.
    """
    if "pvalue" not in epy_df.columns or "qvalue" not in epy_df.columns:
        logger.warning("[%s/%s] missing pvalue/qvalue columns", tool, scenario)
        return {
            "seed": seed, "tool": tool, "test": test, "coverage": coverage,
            "scenario": scenario, "wall_s": wall_s,
            "tp": None, "fp": None, "tn": None, "fn": None,
            "tpr": float("nan"), "fpr": float("nan"),
            "precision": float("nan"), "f1": float("nan"),
            "auroc": float("nan"), "n_dmc_called": None,
            "threshold": Q_THRESHOLD, "threshold_kind": "qvalue",
            "meth_diff_bin": "all", "parameter": "coverage",
            "parameter_value": coverage,
        }

    joined = _join_with_truth(epy_df, truth)
    auroc = _auroc(joined)
    sig = joined.with_columns(sig=pl.col("qvalue") < Q_THRESHOLD)
    m = _confusion(sig, "sig")
    n_called = int(sig.filter(pl.col("sig")).height)

    return {
        "seed": seed, "tool": tool, "test": test, "coverage": coverage,
        "scenario": scenario, "wall_s": wall_s,
        **m, "auroc": auroc, "n_dmc_called": n_called,
        "threshold": Q_THRESHOLD, "threshold_kind": "qvalue",
        "meth_diff_bin": "all", "parameter": "coverage",
        "parameter_value": coverage,
    }


def run_one_cell(
    sample_dir: Path, samplesheet: Path, truth: pl.DataFrame,
    label: str, scenario: str, seed: int | None, coverage: int,
    store_dir: Path,
) -> list[dict]:
    """Run all DMC_TESTS on one cell; return list of scored rows."""
    import epykit as ep

    if store_dir.exists():
        shutil.rmtree(store_dir)

    md = ep.read_bismark(
        str(samplesheet),
        treatment_group="treat",
        control_group="ctrl",
        assembly="sim",
        store_dir=str(store_dir),
    )
    ep.pp.unite(md, type="intersect")

    rows: list[dict] = []
    for test in DMC_TESTS:
        backend_test, kwargs = _dmc_kwargs(test, allow_n1=False)
        tool_label = test.replace("+", "plus")
        tool = f"epykit_{tool_label}"

        t0 = time.perf_counter()
        try:
            ep.tl.dmc(md, **kwargs)
        except ENGINE_EXCEPTIONS as exc:
            elapsed = time.perf_counter() - t0
            logger.error("[%s] DMC test=%s FAILED in %.1fs: %r",
                         label, test, elapsed, exc)
            rows.append({
                "seed": seed, "tool": tool, "test": test,
                "coverage": coverage, "scenario": scenario,
                "wall_s": elapsed,
                "tp": None, "fp": None, "tn": None, "fn": None,
                "tpr": float("nan"), "fpr": float("nan"),
                "precision": float("nan"), "f1": float("nan"),
                "auroc": float("nan"), "n_dmc_called": None,
                "threshold": Q_THRESHOLD, "threshold_kind": "qvalue",
                "meth_diff_bin": "all", "parameter": "coverage",
                "parameter_value": coverage,
                "error": str(exc),
            })
            continue
        elapsed = time.perf_counter() - t0

        df = md.get_dmc(test=backend_test)
        row = _score_cell(
            df, truth, scenario=scenario, seed=seed, coverage=coverage,
            tool=tool, test=test, wall_s=elapsed,
        )
        row.setdefault("error", None)
        rows.append(row)
        logger.info("[%s] %s: %s sites, n_sig=%s, TPR=%.3f, F1=%.3f, AUROC=%.3f, %.1fs",
                    label, tool, f"{df.height:,}", row.get("n_dmc_called"),
                    row.get("tpr") or float("nan"), row.get("f1") or float("nan"),
                    row.get("auroc") or float("nan"), elapsed)

    del md
    gc.collect()
    return rows


# ---------------------------------------------------------------------------
# Driver: headline (N=20) + frozen grid
# ---------------------------------------------------------------------------


def run_headline(seeds: list[int], only_seed: int | None = None) -> list[dict]:
    """Run epykit on every headline seed at cov=10. Returns per-seed rows."""
    all_rows: list[dict] = []
    for seed in seeds:
        if only_seed is not None and seed != only_seed:
            continue
        src_dir = SIM_BASE / f"seed={seed}"
        truth_path = src_dir / "truth.parquet"
        if not truth_path.exists():
            logger.error("missing truth for seed=%d; skip", seed)
            continue

        cache_dir = CONVERT_CACHE / f"seed={seed}"
        _convert_cell(src_dir, HEADLINE_COV, cache_dir)
        sheet = cache_dir / "samplesheet.csv"
        write_samplesheet(cache_dir, n_per_group=N_PER_GROUP, sheet_path=sheet)

        truth = pl.read_parquet(truth_path)
        store_dir = RUN_CACHE / f"seed={seed}"
        logger.info("=== headline seed=%d (cov=%d) ===", seed, HEADLINE_COV)
        rows = run_one_cell(
            cache_dir, sheet, truth,
            label=f"seed{seed}", scenario="simulator_headline",
            seed=seed, coverage=HEADLINE_COV, store_dir=store_dir,
        )
        all_rows.extend(rows)
    return all_rows


def run_frozen_grid(
    frozen_seed: int, only_cov: int | None = None,
) -> list[dict]:
    """Run epykit on the 5-coverage frozen grid at the frozen-defaults seed."""
    all_rows: list[dict] = []
    for cov in FROZEN_GRID_COVS:
        if only_cov is not None and cov != only_cov:
            continue
        src_dir = SIM_BASE / "frozen_grid" / f"cov={cov}"
        truth_path = src_dir / "truth.parquet"
        if not truth_path.exists():
            logger.error("missing truth for frozen cov=%d; skip", cov)
            continue

        cache_dir = CONVERT_CACHE / f"frozen_cov={cov}"
        _convert_cell(src_dir, cov, cache_dir)
        sheet = cache_dir / "samplesheet.csv"
        write_samplesheet(cache_dir, n_per_group=N_PER_GROUP, sheet_path=sheet)

        truth = pl.read_parquet(truth_path)
        store_dir = RUN_CACHE / f"frozen_cov={cov}"
        logger.info("=== frozen_grid cov=%d (seed=%d) ===", cov, frozen_seed)
        rows = run_one_cell(
            cache_dir, sheet, truth,
            label=f"frozen_cov{cov}", scenario="simulator_frozen_grid",
            seed=frozen_seed, coverage=cov, store_dir=store_dir,
        )
        all_rows.extend(rows)
    return all_rows


