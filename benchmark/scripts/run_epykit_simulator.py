"""run_epykit_simulator.py -- Phase 4 Task 3.

Runs epykit on the held-out intrinsic-truth simulator (``benchmark/data/
study1b_simulator/``) for the headline N=20 seeds + the 5-coverage
frozen-defaults grid. The simulator emits a per-CpG ``truth.parquet``
(intrinsic ``is_dmc`` column) but no DMR truth -- only the four
surviving DMC engines (lr, lr+, welch_t, fisher) are scored.

Writes:
  * benchmark/data/study1b_simulator/eval_per_seed.parquet
      One row per (seed, engine) for the N=20 headline seeds (cov=10,
      3v3). 4 engines x 20 seeds = 80 rows nominally.
  * benchmark/data/study1b_simulator/eval_frozen_grid.parquet
      One row per (coverage, engine) for the 5-cov frozen-defaults
      grid at the single seed = 2026100. 4 engines x 5 covs = 20 rows.
  * benchmark/data/study1b_simulator/eval_seed_iqr.parquet
      Median + IQR (Q1/Q3) of TPR/FPR/F1/AUROC across the 20 headline
      seeds, one row per engine. 4 rows.
  * benchmark/data/study1b_simulator/MANIFEST.txt
      Provenance: epykit version, git HEAD, engine kwargs, wallclock.

CIs:
  After writing the parquets the script invokes
  ``evaluate.py --ci-only`` on each summary table. Wilson CIs are
  populated from the integer confusion-matrix counts; bootstrap CIs
  are NaN (no per-CpG cache is materialised for this task).

Determinism:
  Seeds come from ``benchmark/data/seeds.json`` and the data under
  ``benchmark/data/study1b_simulator/`` was generated by
  ``simulate_piao.py`` against those seeds (commit d438b81). Re-running
  this script on the same checkout reproduces the parquets exactly.

Usage:
    uv run python benchmark/scripts/run_epykit_simulator.py
    uv run python benchmark/scripts/run_epykit_simulator.py --only headline:2026000
    uv run python benchmark/scripts/run_epykit_simulator.py --only grid:10
    uv run python benchmark/scripts/run_epykit_simulator.py --skip-ci

Exit non-zero on any per-cell failure.
"""

