def _git_head() -> str:
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT.parent, text=True
        )
        return out.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return "unknown"


def write_manifest(
    per_seed: pl.DataFrame, frozen: pl.DataFrame, iqr: pl.DataFrame,
    total_wall_s: float,
) -> None:
    import epykit as ep

    lines = [
        "study1b_simulator -- Phase 4 Task 3 (run_epykit_simulator.py)",
        "",
        f"Date           : {time.strftime('%Y-%m-%d %H:%M:%S')}",
        f"epykit version : {ep.__version__}",
        "Engine tag     : v0.7.5-phase3-engines-frozen",
        f"Git HEAD       : {_git_head()}",
        "",
        "Held-out intrinsic-truth simulator. The truth table is the",
        "per-CpG is_dmc column emitted by simulate_piao.py; only the four",
        "surviving DMC engines are scored (no DMR truth exists for this",
        "data).",
        "",
        "Engines run: lr, lr+ (power stack), welch_t, fisher.",
        "Skipped    : glm (no covariates), DMR engines (no DMR truth).",
        "",
        "lr+ kwargs (explicit on top of test='lr', single-sourced via",
        "_epykit_scoring._dmc_kwargs):",
        "    neighbour_combine=True, neighbour_bp=500, sep_fallback=True,",
        "    sep_threshold=0.9, fdr_method='fdr_tsbh', dispersion='eb'",
        "",
        "Cells:",
        f"  Headline    : {per_seed.height} rows ({per_seed['seed'].n_unique()} "
        f"seeds x {len(DMC_TESTS)} engines @ cov={HEADLINE_COV})",
        f"  Frozen grid : {frozen.height} rows ({len(FROZEN_GRID_COVS)} covs "
        f"x {len(DMC_TESTS)} engines @ single seed)",
        f"  Seed IQR    : {iqr.height} rows (one per engine; median + Q1/Q3)",
        "",
        f"Total wallclock: {total_wall_s:.1f}s",
        "",
        "Per-engine wallclock (headline only):",
    ]
    if per_seed.height:
        per_engine = (
            per_seed.group_by("tool").agg(
                pl.len().alias("n_cells"),
                pl.col("wall_s").sum().alias("total_s"),
                pl.col("wall_s").median().alias("median_s"),
            )
            .sort("tool")
        )
        for r in per_engine.iter_rows(named=True):
            lines.append(
                f"  {r['tool']:<28}  n={r['n_cells']:<3}  "
                f"total={r['total_s']:.1f}s  median={r['median_s']:.2f}s"
            )

    def _rel(p: Path) -> str:
        # Best-effort relative path; tolerates test redirection to /tmp on
        # a different drive letter (Windows) where ``relative_to`` raises.
        try:
            return str(p.relative_to(ROOT.parent))
        except ValueError:
            return str(p)

    lines += [
        "",
        "Outputs:",
        f"  - {_rel(EVAL_PER_SEED)}",
        f"  - {_rel(EVAL_FROZEN_GRID)}",
        f"  - {_rel(EVAL_SEED_IQR)}",
        "",
        "Methods seeds:",
        "  - headline_seeds: see benchmark/data/seeds.json",
        "  - frozen_defaults_seed: single seed at",
        "      benchmark/data/study1b_simulator/frozen_grid/",
        "",
        "Per-cell intermediate parquets (converted .cov.gz + methylstore",
        "caches) live under benchmark/_converted_simulator/ and",
        "benchmark/_runs_simulator/. Both are gitignored bulk artefacts;",
        "regenerable via this script.",
        "",
    ]
    MANIFEST_PATH.write_text("\n".join(lines), encoding="utf-8")
    logger.info("wrote %s", MANIFEST_PATH)


