def compute_seed_iqr(per_seed: pl.DataFrame) -> pl.DataFrame:
    """Median + IQR (Q1/Q3) of TPR/FPR/F1/AUROC across seeds, per engine.

    Only successful cells (non-null TPR) contribute. Engines that failed
    on every seed are dropped (no row emitted).
    """
    df = per_seed.filter(pl.col("tpr").is_not_null())
    if df.height == 0:
        return pl.DataFrame(schema={
            "tool": pl.Utf8, "n_seeds": pl.Int64,
            "tpr_median": pl.Float64, "tpr_q1": pl.Float64, "tpr_q3": pl.Float64,
            "fpr_median": pl.Float64, "fpr_q1": pl.Float64, "fpr_q3": pl.Float64,
            "f1_median": pl.Float64, "f1_q1": pl.Float64, "f1_q3": pl.Float64,
            "auroc_median": pl.Float64, "auroc_q1": pl.Float64, "auroc_q3": pl.Float64,
        })
    return (
        df.group_by("tool").agg(
            pl.len().alias("n_seeds"),
            pl.col("tpr").median().alias("tpr_median"),
            pl.col("tpr").quantile(0.25).alias("tpr_q1"),
            pl.col("tpr").quantile(0.75).alias("tpr_q3"),
            pl.col("fpr").median().alias("fpr_median"),
            pl.col("fpr").quantile(0.25).alias("fpr_q1"),
            pl.col("fpr").quantile(0.75).alias("fpr_q3"),
            pl.col("f1").median().alias("f1_median"),
            pl.col("f1").quantile(0.25).alias("f1_q1"),
            pl.col("f1").quantile(0.75).alias("f1_q3"),
            pl.col("auroc").median().alias("auroc_median"),
            pl.col("auroc").quantile(0.25).alias("auroc_q1"),
            pl.col("auroc").quantile(0.75).alias("auroc_q3"),
        )
        .sort("tool")
    )


def add_ci_via_evaluate(parquet_path: Path) -> None:
    """Append Wilson + bootstrap CI columns via the sealed evaluate.py.

    Splits rows with valid tp/fp/tn/fn from rows without (the latter
    cannot be Wilson-CI'd; they get NaN CI columns and are concatenated
    back). This is the same pattern used in run_epykit_study1.py and
    documented in _epykit_scoring.split_for_ci.
    """
    df = pl.read_parquet(parquet_path)
    has_counts, no_counts = split_for_ci(df)
    logger.info("[%s] CI split: %d with counts, %d without",
                parquet_path.name, has_counts.height, no_counts.height)

    if has_counts.height == 0:
        logger.warning("[%s] no rows with counts; skip CI append", parquet_path.name)
        return

    tmp = parquet_path.with_suffix(".ci_tmp.parquet")
    has_counts.write_parquet(tmp)
    evaluate_script = HERE / "evaluate.py"
    proc = subprocess.run(
        [sys.executable, str(evaluate_script),
         "--ci-only", "--eval-summary", str(tmp)],
        check=False, capture_output=True, text=True,
    )
    if proc.returncode != 0:
        tmp.unlink(missing_ok=True)
        raise RuntimeError(
            f"evaluate.py --ci-only FAILED on {parquet_path.name}:\n{proc.stderr}"
        )
    with_ci = pl.read_parquet(tmp)
    tmp.unlink(missing_ok=True)

    if no_counts.height:
        for c in ("tpr_ci_lo", "tpr_ci_hi", "fpr_ci_lo", "fpr_ci_hi",
                  "auroc_ci_lo", "auroc_ci_hi", "f1_ci_lo", "f1_ci_hi"):
            if c not in no_counts.columns:
                no_counts = no_counts.with_columns(
                    pl.lit(float("nan")).alias(c).cast(pl.Float64)
                )
        all_cols = with_ci.columns
        no_counts = no_counts.select(all_cols)
        final = pl.concat([with_ci, no_counts], how="vertical_relaxed")
    else:
        final = with_ci
    final.write_parquet(parquet_path)
    logger.info("[%s] wrote %d rows with CI columns",
                parquet_path.name, final.height)


