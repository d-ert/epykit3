def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--only", default=None,
        help="Run a single cell. 'headline:<seed>' or 'grid:<cov>'.",
    )
    parser.add_argument(
        "--skip-headline", action="store_true",
        help="Skip headline N=20 sweep (e.g. resume frozen grid only).",
    )
    parser.add_argument(
        "--skip-grid", action="store_true",
        help="Skip frozen-defaults grid sweep.",
    )
    parser.add_argument(
        "--skip-ci", action="store_true",
        help="Don't run evaluate.py --ci-only at the end.",
    )
    parser.add_argument(
        "--verbose", "-v", action="store_true",
        help="DEBUG-level logging.",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        force=True,
    )

    SIM_BASE.mkdir(parents=True, exist_ok=True)
    CONVERT_CACHE.mkdir(parents=True, exist_ok=True)
    RUN_CACHE.mkdir(parents=True, exist_ok=True)

    headline_seeds, frozen_seed = load_seeds()
    logger.info("loaded %d headline seeds; frozen seed = %d",
                len(headline_seeds), frozen_seed)

    only_headline: int | None = None
    only_grid: int | None = None
    if args.only:
        if args.only.startswith("headline:"):
            only_headline = int(args.only.split(":", 1)[1])
            args.skip_grid = True
        elif args.only.startswith("grid:"):
            only_grid = int(args.only.split(":", 1)[1])
            args.skip_headline = True
        else:
            raise SystemExit(f"--only expects 'headline:<seed>' or 'grid:<cov>', got {args.only!r}")

    t0 = time.perf_counter()
    headline_rows: list[dict] = []
    grid_rows: list[dict] = []
    n_fail = 0

    if not args.skip_headline:
        headline_rows = run_headline(headline_seeds, only_seed=only_headline)
        n_fail += sum(1 for r in headline_rows if r.get("error"))
        if headline_rows:
            per_seed_df = pl.DataFrame(headline_rows)
            EVAL_PER_SEED.parent.mkdir(parents=True, exist_ok=True)
            # Merge with any existing file when --only was used.
            if EVAL_PER_SEED.exists() and only_headline is not None:
                old = pl.read_parquet(EVAL_PER_SEED)
                seeds_done = per_seed_df["seed"].unique().to_list()
                old = old.filter(~pl.col("seed").is_in(seeds_done))
                per_seed_df = pl.concat(
                    [old, per_seed_df], how="diagonal_relaxed",
                )
            per_seed_df.write_parquet(EVAL_PER_SEED)
            logger.info("wrote %s (%d rows)", EVAL_PER_SEED, per_seed_df.height)

    if not args.skip_grid:
        grid_rows = run_frozen_grid(frozen_seed, only_cov=only_grid)
        n_fail += sum(1 for r in grid_rows if r.get("error"))
        if grid_rows:
            grid_df = pl.DataFrame(grid_rows)
            EVAL_FROZEN_GRID.parent.mkdir(parents=True, exist_ok=True)
            if EVAL_FROZEN_GRID.exists() and only_grid is not None:
                old = pl.read_parquet(EVAL_FROZEN_GRID)
                covs_done = grid_df["coverage"].unique().to_list()
                old = old.filter(~pl.col("coverage").is_in(covs_done))
                grid_df = pl.concat([old, grid_df], how="diagonal_relaxed")
            grid_df.write_parquet(EVAL_FROZEN_GRID)
            logger.info("wrote %s (%d rows)", EVAL_FROZEN_GRID, grid_df.height)

    # IQR aggregate -- always recompute from whatever's now on disk so
    # partial reruns stay consistent.
    if EVAL_PER_SEED.exists():
        per_seed_disk = pl.read_parquet(EVAL_PER_SEED)
        iqr_df = compute_seed_iqr(per_seed_disk)
        EVAL_SEED_IQR.parent.mkdir(parents=True, exist_ok=True)
        iqr_df.write_parquet(EVAL_SEED_IQR)
        logger.info("wrote %s (%d rows)", EVAL_SEED_IQR, iqr_df.height)

    # CI columns
    if not args.skip_ci:
        if EVAL_PER_SEED.exists():
            add_ci_via_evaluate(EVAL_PER_SEED)
        if EVAL_FROZEN_GRID.exists():
            add_ci_via_evaluate(EVAL_FROZEN_GRID)

    total_wall = time.perf_counter() - t0

    # Manifest
    per_seed_final = (
        pl.read_parquet(EVAL_PER_SEED) if EVAL_PER_SEED.exists()
        else pl.DataFrame()
    )
    frozen_final = (
        pl.read_parquet(EVAL_FROZEN_GRID) if EVAL_FROZEN_GRID.exists()
        else pl.DataFrame()
    )
    iqr_final = (
        pl.read_parquet(EVAL_SEED_IQR) if EVAL_SEED_IQR.exists()
        else pl.DataFrame()
    )
    write_manifest(per_seed_final, frozen_final, iqr_final, total_wall)

    # Also write a timings sidecar for debugging (gitignored).
    timings_rows = headline_rows + grid_rows
    if timings_rows:
        timings_df = pl.DataFrame(
            [{"seed": r.get("seed"), "coverage": r.get("coverage"),
              "scenario": r.get("scenario"), "tool": r.get("tool"),
              "wall_s": r.get("wall_s"),
              "ok": r.get("error") is None,
              "error": r.get("error")}
             for r in timings_rows]
        )
        timings_df.write_parquet(TIMINGS_PATH)

    if n_fail:
        logger.error("%d cell-engine combinations FAILED", n_fail)
    logger.info("total wallclock: %.1fs", total_wall)
    return 1 if n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
